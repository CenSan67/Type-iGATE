import React from 'react'
import { useAuth } from '../../context/AuthContext'
import PrintPreviewFrame from './PrintPreviewFrame'
import bsuLogo from '../../assets/bsu_logo-removebg-preview.png'
import { formatLongDate } from '../../utils/reportBuilders'

// Print preview for a tabular report (letterhead, meta, table, summary box, footer) modelled on
// the "Report & Printing Module" mockup. Data comes from utils/reportBuilders.js.
export default function PrintReportModal({ title, dateRange, columns, rows, summary, onClose }){
  const { user, profile } = useAuth()
  const generatedBy = profile?.fullName || profile?.displayName || user?.email || '—'

  return (
    <PrintPreviewFrame onClose={onClose}>
      <div className="print-report-sheet">
        <img src={bsuLogo} alt="" className="print-report-watermark" />

        <header className="print-report-letterhead">
          <img src={bsuLogo} alt="Bulacan State University Seal" />
          <div>
            <h1>Bulacan State University</h1>
            <p>Intelligent Gate Access &amp; Tracking - BulSU Bustos Campus</p>
          </div>
        </header>

        <h2 className="print-report-title">{title}</h2>
        <div className="print-report-meta">
          <div>Date Range: {dateRange}</div>
          <div>Generated On: {formatLongDate(Date.now())}</div>
          <div>Generated By: {generatedBy}</div>
        </div>

        <table className="print-report-table">
          <thead>
            <tr>{columns.map((col) => <th key={col.key}>{col.label}</th>)}</tr>
          </thead>
          <tbody>
            {rows.length === 0 ? (
              <tr><td colSpan={columns.length} className="print-report-empty">No records match the current filters.</td></tr>
            ) : rows.map((row, i) => (
              <tr key={i}>
                {columns.map((col) => (
                  <td key={col.key}>
                    {col.type === 'direction'
                      ? <span className={`print-badge ${row[col.key] === 'OUT' ? 'out' : 'in'}`}>{row[col.key] === 'OUT' ? '- OUT' : '+ IN'}</span>
                      : row[col.key] ?? '—'}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>

        <div className="print-report-summary">
          {summary.map((item) => <span key={item.label}>{item.label}: <strong>{item.value}</strong></span>)}
        </div>

        <p className="print-report-footer">This is a system-generated report.</p>
      </div>
    </PrintPreviewFrame>
  )
}
